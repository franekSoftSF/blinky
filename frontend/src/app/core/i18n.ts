export type MessageKey = keyof typeof messages.pl;

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly language = signal<Language>(
    (localStorage.getItem('blinky.language') as Language) === 'en' ? 'en' : 'pl',
  );
  readonly locale = computed(() => (this.language() === 'pl' ? 'pl-PL' : 'en-GB'));
  t(key: MessageKey): string {
    return messages[this.language()][key];
  }
  use(language: Language): void {
    this.language.set(language);
    localStorage.setItem('blinky.language', language);
    document.documentElement.lang = language;
  }
  toggle(): void {
    this.use(this.language() === 'pl' ? 'en' : 'pl');
  }
}
